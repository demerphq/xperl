package Diag::Pack;

use strict;
use warnings;

# Use diag.pl's validated analysis and table writers. This module selects one
# or more languages and emits their ordinary XS distribution scaffolds.

# Build language-local tables from the shared schema and validated source.
sub _render_data {
    my ( $diagnostics, $diag_table, $language, $selector_layouts, $language_layouts,
        $language_config, $plural_rules, $template_analysis, $words )
      = @_;
    my $text = '';
    open my $out, '>', \$text or die "Cannot buffer $language diagnostic pack: $!\n";

    print {$out} "STATIC_ASSERT_DECL(OP_max + 2 == ", scalar( @{ $words->{operations} } ) + 1,
      "); /* compiled operation-map bound */\n\n";
    print {$out} "enum { perl_diag_lang_none = 0, perl_diag_lang_$language = 1 };\n\n";
    main::write_pack_operation_names( $out, $words->{operations} );
    my @word_diagnostics = grep { $_->{operation_words} }
      sort { $a->{number} <=> $b->{number} } @$diag_table;
    my @word_group_ids =
      ( [ 'perl_diag_word_group_none', 0 ], map { [ 'perl_diag_word_group_' . $_->{number}, '' ] } @word_diagnostics );
    print {$out} "enum {\n", main::render_enum_rows( \@word_group_ids ), "};\n\n";
    my $pack_config = { $language => $language_config->{$language} };
    main::write_plural_macros( $out, [$language], $pack_config, $plural_rules );
    my $registry = main::new_selector_definition_registry($selector_layouts);
    my $selector_definitions = main::write_selector_definitions(
        $out, $diagnostics, $language_layouts, $registry, $language );
    my $template_names       = main::write_template_texts( $out, $diagnostics, $template_analysis, $words, $language );
    print {$out} "enum {\n", main::render_enum_rows( [ [ 'perl_diag_template_no_template', 0 ] ] ), "};\n\n";

    my $word_bindings = main::write_word_tables( $out, $language, $words, $diag_table, $template_names );
    my @groups        = ( [ 0, 'NULL' ], map { $word_bindings->{ $_->{code} } || [ 0, 'NULL' ] } @word_diagnostics );
    print {$out} "static const perl_diag_word_group_t perl_diag_word_groups_$language\[\] = {\n",
      main::render_struct_rows( \@groups, { 0 => 'no word bindings' } ), "};\n\n";
    my $schema_registry = {};
    main::write_language_tables( $out, $diag_table, {}, $language, $language_layouts,
        $selector_definitions, $template_names, $template_analysis, $schema_registry );
    main::write_selector_domain_table( $out, $registry );
    print {$out} main::render_pack_catalog_definition(
        $language, 1, "perl_diagpack_catalog_$language");

    close $out or die "Cannot close $language diagnostic pack buffer: $!\n";
    my $body_digest = Digest::SHA::sha256_hex( Encode::encode( 'UTF-8', $text ) );
    return "/* Language-scoped rendered data SHA-256: $body_digest */\n\n$text";
}

sub _render_xs {
    my ( $language, $module ) = @_;
    my $id = lc $language;
    my $engine_definition = main::render_pack_engine_definition(
        $id, "perl_diagpack_catalog_$id", "perl_diagpack_${id}_engine",
        'Perl_diagpack');
    return <<"XS";
/* Generated by regen/diag.pl. Do not edit. */
#include "EXTERN.h"
#include "perl.h"
#include "XSUB.h"
#include "diagpack.h"
#include "${language}_data.inc"

$engine_definition

MODULE = $module    PACKAGE = $module

PROTOTYPES: DISABLE

BOOT:
    CV *metadata_cv = get_cv("${module}::metadata", 0);
    CV *render_cv = get_cv("${module}::render", 0);
    if (!metadata_cv || !render_cv)
        PERL_THROW_ERROR_DIAGNOSTIC_API_RENDER_INPUT_INVALID();
    Perl_diagpack_register(aTHX_ &perl_diagpack_${id}_engine);
    CvXSUBANY(metadata_cv).any_ptr = (void *)&perl_diagpack_${id}_engine;
    CvXSUBANY(render_cv).any_ptr = (void *)&perl_diagpack_${id}_engine;

SV *
metadata(self)
    SV *self
  CODE:
    PERL_UNUSED_ARG(self);
    RETVAL = Perl_diagpack_metadata(aTHX_
        (const perl_diagpack_engine *)CvXSUBANY(cv).any_ptr);
  OUTPUT:
    RETVAL

SV *
render(self, diagnostic)
    SV *self
    SV *diagnostic
  CODE:
    PERL_UNUSED_ARG(self);
    RETVAL = Perl_diagpack_render_diagnostic(aTHX_
        (const perl_diagpack_engine *)CvXSUBANY(cv).any_ptr, diagnostic);
    if (!RETVAL)
        RETVAL = newSV(0);
  OUTPUT:
    RETVAL
XS
}

sub _write_distribution {
    my ( $language, $data, $root ) = @_;
    my $uppercase = uc $language;
    my $module    = "XPerl::DiagPack::$uppercase";
    my $directory = "$root/ext/XPerl-DiagPack-$uppercase";
    mkdir $directory unless -d $directory;
    main::write_generated_output(
        "$directory/${uppercase}_data.inc", $data,
        [qw(regen/diag.pl regen/diag_lib.pm regen/diag_words.pm regen/diag_pack.pm regen/regen_lib.pl regen/opcodes)]
    );
    main::write_plain_output( "$directory/$uppercase.xs", _render_xs( $uppercase, $module ), 0 );
    my $language_name = $language;
    main::write_plain_output( "$directory/$uppercase.pm", <<"PM", 0 );
package $module;

=head1 NAME

$module - diagnostic language pack for $language_name

=head1 DESCRIPTION

Loads the diagnostic catalog for language C<$language_name> and registers it as
an available capability. Loading the module does not change the selected
diagnostic language.

=head1 METHODS

=over 4

=item metadata

Returns the language and descriptor ABI metadata.

=item render(\$diagnostic)

Returns the message body rendered with this pack's catalog, or C<undef> when
the pack has no complete rendering. It does not select a language, apply a
fallback, add locations or grouping, invoke hooks, or deliver a diagnostic.

The catalog uses the core diagnostic's retained semantic parameters.
Registration checks the schema of each supplied diagnostic. Missing rows
or a missing complete translation return C<undef>.

=back

=cut

use strict;
use warnings;

our \$VERSION = '0.01';
require XSLoader;
XSLoader::load(__PACKAGE__, \$VERSION);

1;
PM
    main::write_plain_output( "$directory/Makefile.PL", <<"MAKE", 0 );
use ExtUtils::MakeMaker;

WriteMakefile(
    NAME         => '$module',
    VERSION_FROM => '$uppercase.pm',
    INC          => '-I../..',
    PREREQ_PM    => {},
    depend       => { '${uppercase}\$(OBJ_EXT)' => '${uppercase}_data.inc' },
);
MAKE
}

sub generate {
    my ( $languages, $diagnostics, $diag_table, $selector_layouts, $language_config, $plural_rules, $root ) = @_;

    my $template_analysis = main::build_template_analysis($diagnostics);
    my %selector_layouts_by_language = map {
        $_ => main::build_language_selector_layouts(
            $diagnostics, $_, $selector_layouts, Diag::Words::catalog() )
    } @$languages;
    my $words             = Diag::Words::compile( $diagnostics, undef, \%selector_layouts_by_language );
    for my $language (@$languages) {
        my $data = _render_data( $diagnostics, $diag_table, $language, $selector_layouts,
            $selector_layouts_by_language{$language},
            $language_config, $plural_rules, $template_analysis, $words );
        _write_distribution( $language, $data, $root );
    }
}

1;
