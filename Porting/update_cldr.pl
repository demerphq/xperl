#!/usr/bin/perl
use strict;
use warnings;
use utf8;
use JSON::PP;
use Encode qw(encode);
use Data::Dumper;
use Digest::SHA qw(sha256_hex);
use File::Copy qw(copy);
use File::Path qw(make_path);
use File::Spec;
use Getopt::Long qw(GetOptions);

my $output_dir = File::Spec->catdir('lib', 'unicore', 'cldr');
my ($source_dir, $check, $help);
GetOptions(
    'source-dir=s'  => \$source_dir,
    'output-dir=s'  => \$output_dir,
    'check'         => \$check,
    'help'          => \$help,
) or usage(2);
usage(0) if $help;
usage(2) if $check && defined $source_dir;

my @files = qw(package.json LICENSE plurals.json ordinals.json);
my $input_dir = defined $source_dir
    ? $source_dir
    : $output_dir;

my %input;
for my $file (@files) {
    my $path = File::Spec->catfile($input_dir, $file);
    if ($file eq 'plurals.json' || $file eq 'ordinals.json') {
        $path = File::Spec->catfile($input_dir, $file);
        $path = File::Spec->catfile($input_dir, 'supplemental', $file)
            if !-f $path && -f File::Spec->catfile($input_dir, 'supplemental', $file);
    }
    open my $fh, '<:raw', $path or die "Cannot read $path: $!\n";
    local $/;
    $input{$file} = <$fh>;
    close $fh or die "Cannot close $path: $!\n";
}

my $package = decode_json($input{'package.json'});
die "Expected cldr-core package metadata\n"
    unless ref($package) eq 'HASH' && $package->{name} eq 'cldr-core'
        && defined $package->{version} && $package->{version} =~ /\A\d+\.\d+\.\d+\z/;
my $cldr_version = $package->{cldrVersion};
die "Package version and CLDR version disagree\n"
    unless defined $cldr_version && $cldr_version =~ /\A\d+\z/
        && $package->{version} =~ /\A\Q$cldr_version\E\./;

if (!defined $source_dir) {
    my $version_file = File::Spec->catfile($output_dir, 'version');
    open my $fh, '<:raw', $version_file or die "Cannot read $version_file: $!\n";
    my $selected = <$fh>;
    close $fh;
    $selected =~ s/\s+\z// if defined $selected;
    die "CLDR version file does not match package metadata\n"
        unless defined $selected && $selected eq $cldr_version;
}

my %decoded;
for my $file (qw(plurals.json ordinals.json)) {
    $decoded{$file} = decode_json($input{$file});
    my $version = $decoded{$file}{supplemental}{version};
    die "$file has no supplemental version metadata\n"
        unless ref($version) eq 'HASH'
            && defined $version->{_cldrVersion}
            && defined $version->{_unicodeVersion};
    die "$file CLDR version does not match package metadata\n"
        unless "$version->{_cldrVersion}" eq "$cldr_version";
    die "$file Unicode version does not match package metadata\n"
        unless $version->{_unicodeVersion} eq $package->{unicodeVersion};
}

my @categories = qw(zero one two few many other);
my %category_order = map { ("pluralRule-count-$_" => $_) } @categories;
my $cardinal = extract_plural_type($decoded{'plurals.json'}, 'plurals-type-cardinal');
my $ordinal = extract_plural_type($decoded{'ordinals.json'}, 'plurals-type-ordinal');
my ($plural_parents_bytes, $plural_parents) = load_plural_parents(
    $source_dir, $output_dir, $cldr_version, $package->{unicodeVersion},
    $cardinal, $ordinal,
);
my %data = (
    version => {
        cldr => $cldr_version,
        package => $package->{version},
        unicode => $package->{unicodeVersion},
    },
    provenance => {
        package => 'cldr-core from unicode-org/cldr-json',
        source => 'https://github.com/unicode-org/cldr-json',
        license => 'Unicode-3.0',
        sha256 => {
            (map { $_ => sha256_hex($input{$_}) } @files),
            'pluralParents.json' => sha256_hex($plural_parents_bytes),
        },
        plural_parent_source => $plural_parents->{source},
    },
    categories => \@categories,
    cardinal => $cardinal,
    ordinal => $ordinal,
    plural_parents => $plural_parents->{pluralParents},
);

my $dump = Data::Dumper->new([\%data], ['CLDR_DATA'])
    ->Terse(0)->Indent(1)->Sortkeys(1)->Useqq(1)->Useperl(1)->Dump;
my $generated = "# Generated by Porting/update_cldr.pl. Do not edit.\n"
    . "our \$CLDR_DATA;\n" . $dump . "1;\n";
my $generated_bytes = encode('UTF-8', $generated);

if ($check) {
    my $output = File::Spec->catfile($output_dir, 'plural.pl');
    open my $fh, '<:raw', $output or die "Cannot read $output: $!\n";
    local $/;
    my $actual = <$fh>;
    close $fh;
    die "$output is out of date; run Porting/update_cldr.pl\n"
        unless $actual eq $generated_bytes;
    exit 0;
}

make_path($output_dir) unless -d $output_dir;
if (defined $source_dir) {
    for my $file (@files) {
        my $src = File::Spec->catfile($source_dir, $file);
        $src = File::Spec->catfile($source_dir, 'supplemental', $file)
            if !-f $src && -f File::Spec->catfile($source_dir, 'supplemental', $file);
        my $dst = File::Spec->catfile($output_dir, $file);
        copy($src, $dst) or die "Cannot copy $src to $dst: $!\n";
    }
    my $version_file = File::Spec->catfile($output_dir, 'version');
    open my $version_fh, '>:raw', $version_file
        or die "Cannot write $version_file: $!\n";
    print {$version_fh} "$cldr_version\n"
        or die "Cannot write $version_file: $!\n";
    close $version_fh or die "Cannot close $version_file: $!\n";

    my $parents_file = File::Spec->catfile($output_dir, 'pluralParents.json');
    open my $parents_fh, '>:raw', $parents_file
        or die "Cannot write $parents_file: $!\n";
    print {$parents_fh} $plural_parents_bytes
        or die "Cannot write $parents_file: $!\n";
    close $parents_fh or die "Cannot close $parents_file: $!\n";
}
my $output = File::Spec->catfile($output_dir, 'plural.pl');
open my $fh, '>:raw', $output or die "Cannot write $output: $!\n";
print {$fh} $generated_bytes or die "Cannot write $output: $!\n";
close $fh or die "Cannot close $output: $!\n";

sub extract_plural_type {
    my ($document, $key) = @_;
    my $locales = $document->{supplemental}{$key};
    die "Missing $key\n" unless ref($locales) eq 'HASH' && keys %$locales;
    my (%rules, %locale_rules, %rule_id);
    for my $locale (sort keys %$locales) {
        die "Invalid locale id '$locale' in $key\n"
            unless $locale =~ /\A[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\z/;
        my $source_rules = $locales->{$locale};
        die "Invalid rules for locale $locale in $key\n" unless ref($source_rules) eq 'HASH';
        my %locale_rule;
        for my $source_category (keys %$source_rules) {
            die "Unknown category $source_category for locale $locale\n"
                unless exists $category_order{$source_category};
            my $category = $category_order{$source_category};
            my $source_text = $source_rules->{$source_category};
            die "Invalid rule text for $locale/$category\n" unless defined $source_text && !ref($source_text);
            my ($condition, $integer_text, $decimal_text) = parse_rule_text($source_text);
            die "The other category must have an empty condition for $locale\n"
                if $category eq 'other' && length $condition;
            die "The $category category must have a condition for $locale\n"
                if $category ne 'other' && !length $condition;
            $locale_rule{$category} = {
                condition => $condition,
                integer_samples => parse_samples($integer_text, $locale, $category),
                decimal_samples_text => $decimal_text,
            };
        }
        die "Locale $locale has no other category\n" unless exists $locale_rule{other};
        my $canonical = canonical_rule_set(\%locale_rule);
        my $id = $rule_id{$canonical};
        if (!defined $id) {
            $id = sprintf 'r%03d', scalar(keys %rules);
            $rule_id{$canonical} = $id;
            $rules{$id} = \%locale_rule;
        }
        $locale_rules{$locale} = $id;
    }
    return { locales => \%locale_rules, rules => \%rules };
}

sub load_plural_parents {
    my ($source_dir, $output_dir, $cldr_version, $unicode_version,
        $cardinal, $ordinal) = @_;
    my ($bytes, $parent_data);
    if (defined $source_dir) {
        my $full_path = File::Spec->catfile($source_dir, 'supplemental', 'parentLocales.json');
        my $source_path = 'supplemental/parentLocales.json';
        if (!-f $full_path) {
            $full_path = File::Spec->catfile($source_dir, 'parentLocales.json');
            $source_path = 'parentLocales.json';
        }
        if (-f $full_path) {
            my $raw = read_file($full_path);
            my $document = decode_json($raw);
            my $version = $document->{supplemental}{version};
            die "parentLocales.json has no supplemental version metadata\n"
                unless ref($version) eq 'HASH'
                    && defined $version->{_cldrVersion}
                    && defined $version->{_unicodeVersion};
            die "parentLocales.json CLDR version does not match package metadata\n"
                unless "$version->{_cldrVersion}" eq "$cldr_version";
            die "parentLocales.json Unicode version does not match package metadata\n"
                unless $version->{_unicodeVersion} eq $unicode_version;
            my $raw_parents = $document->{supplemental}{parentLocales};
            die "Missing parentLocales data\n" unless ref($raw_parents) eq 'HASH';
            my $general = $raw_parents->{parentLocale};
            my $plural = $raw_parents->{plurals};
            die "Invalid general parent locale map\n" unless ref($general) eq 'HASH';
            die "Invalid plural-specific parent locale map\n" unless ref($plural) eq 'HASH';
            my %parents = %$general;
            $parents{$_} = $plural->{$_} for keys %$plural;
            validate_parent_map(\%parents);
            $parent_data = {
                version => "$cldr_version",
                source => {
                    path => $source_path,
                    sha256 => sha256_hex($raw),
                },
                pluralParents => {
                    cardinal => filter_plural_parents(\%parents, $cardinal),
                    ordinal => filter_plural_parents(\%parents, $ordinal),
                },
            };
            $bytes = JSON::PP->new->canonical->pretty->utf8->encode($parent_data);
        }
        else {
            my $reduced_path = File::Spec->catfile($source_dir, 'pluralParents.json');
            $bytes = read_file($reduced_path);
            $parent_data = decode_json($bytes);
        }
    }
    else {
        my $reduced_path = File::Spec->catfile($output_dir, 'pluralParents.json');
        $bytes = read_file($reduced_path);
        $parent_data = decode_json($bytes);
    }
    validate_plural_parent_subset($parent_data, $cldr_version, $cardinal, $ordinal);
    return ($bytes, $parent_data);
}

sub filter_plural_parents {
    my ($parents, $plural_type) = @_;
    my %filtered;
    for my $locale (sort keys %$parents) {
        next unless $locale =~ /(?:\A|-)(?:[A-Z]{2}|[0-9]{3})(?:-|\z)/;
        next if exists $plural_type->{locales}{$locale};
        my $target = resolve_parent_rule_locale(
            $parents, $locale, $plural_type->{locales},
        );
        next unless defined $target;
        next if $target eq 'root' || $target eq 'und';
        my $normal = resolve_stripped_rule_locale($locale, $plural_type->{locales});
        next unless defined $normal;
        next if same_plural_rules(
            $plural_type->{locales}{$target},
            $plural_type->{locales}{$normal},
            $plural_type->{rules},
        );
        $filtered{$locale} = $target;
    }
    return \%filtered;
}

sub resolve_parent_rule_locale {
    my ($parents, $locale, $rule_locales) = @_;
    my %seen = ($locale => 1);
    my $candidate = $parents->{$locale};
    while (defined $candidate) {
        die "Cycle in plural parent locale chain at $candidate\n"
            if $seen{$candidate}++;
        return $candidate if exists $rule_locales->{$candidate};
        if (exists $parents->{$candidate}) {
            $candidate = $parents->{$candidate};
        }
        else {
            $candidate =~ s/-[^-]+\z// or return;
        }
    }
    return;
}

sub resolve_stripped_rule_locale {
    my ($locale, $rule_locales) = @_;
    while (defined $locale) {
        return $locale if exists $rule_locales->{$locale};
        $locale =~ s/-[^-]+\z// or return;
    }
    return;
}

sub same_plural_rules {
    my ($left_id, $right_id, $rules) = @_;
    my ($left, $right) = ($rules->{$left_id}, $rules->{$right_id});
    for my $category (@categories) {
        my $has_left = exists $left->{$category};
        my $has_right = exists $right->{$category};
        return 0 if $has_left != $has_right;
        next unless $has_left;
        return 0 if $left->{$category}{condition} ne $right->{$category}{condition};
    }
    return 1;
}

sub validate_parent_map {
    my ($parents) = @_;
    for my $locale (keys %$parents) {
        die "Invalid parent locale id '$locale'\n"
            unless $locale =~ /\A[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\z/;
        my $parent = $parents->{$locale};
        die "Invalid parent locale for $locale\n"
            unless defined $parent && !ref($parent)
                && $parent =~ /\A[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\z/;
        my %seen;
        my $current = $locale;
        while (exists $parents->{$current}) {
            die "Cycle in plural parent locale chain at $current\n"
                if $seen{$current}++;
            $current = $parents->{$current};
        }
    }
}

sub validate_plural_parent_subset {
    my ($subset, $cldr_version, $cardinal, $ordinal) = @_;
    die "Invalid plural parent subset\n" unless ref($subset) eq 'HASH';
    die "Plural parent subset CLDR version does not match package metadata\n"
        unless defined $subset->{version} && "$subset->{version}" eq "$cldr_version";
    die "Invalid plural parent provenance\n"
        unless ref($subset->{source}) eq 'HASH'
            && defined $subset->{source}{path} && !ref($subset->{source}{path})
            && $subset->{source}{path} =~ /\A[A-Za-z0-9_.\/-]+\z/
            && defined $subset->{source}{sha256}
            && $subset->{source}{sha256} =~ /\A[0-9a-f]{64}\z/;
    my $mappings = $subset->{pluralParents};
    die "Invalid plural parent mappings\n" unless ref($mappings) eq 'HASH';
    die "Unexpected plural parent mapping kind\n"
        if grep { $_ ne 'cardinal' && $_ ne 'ordinal' } keys %$mappings;
    my %expected = (cardinal => $cardinal, ordinal => $ordinal);
    for my $kind (qw(cardinal ordinal)) {
        my $parents = $mappings->{$kind};
        die "Invalid $kind parent locale mappings\n" unless ref($parents) eq 'HASH';
        for my $locale (keys %$parents) {
            my $target = $parents->{$locale};
            die "Invalid $kind plural parent locale id '$locale'\n"
                unless $locale =~ /\A[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\z/
                    && $locale =~ /(?:\A|-)(?:[A-Z]{2}|[0-9]{3})(?:-|\z)/;
            die "Invalid $kind plural parent target for $locale\n"
                unless defined $target && !ref($target)
                    && $target =~ /\A[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\z/
                    && $target ne 'root' && $target ne 'und';
            die "$kind parent source $locale has an explicit rule row\n"
                if exists $expected{$kind}{locales}{$locale};
            die "$kind parent target $target has no explicit rule row\n"
                unless exists $expected{$kind}{locales}{$target};
            my $normal = resolve_stripped_rule_locale($locale, $expected{$kind}{locales});
            die "$kind parent source $locale has no normal explicit rule row\n"
                unless defined $normal;
            die "$kind parent mapping for $locale does not change the rule set\n"
                if same_plural_rules(
                    $expected{$kind}{locales}{$target},
                    $expected{$kind}{locales}{$normal},
                    $expected{$kind}{rules},
                );
        }
    }
}

sub read_file {
    my ($path) = @_;
    open my $fh, '<:raw', $path or die "Cannot read $path: $!\n";
    local $/;
    my $contents = <$fh>;
    close $fh or die "Cannot close $path: $!\n";
    return $contents;
}

sub parse_rule_text {
    my ($text) = @_;
    die "Invalid plural sample annotation\n"
        if $text =~ /\@(?!integer\b|decimal\b)/;
    my @annotations;
    while ($text =~ /\@(integer|decimal)\b/g) {
        push @annotations, [$1, $-[0], $+[0]];
    }
    my %seen;
    for my $annotation (@annotations) {
        die "Duplicate \@$annotation->[0] annotation\n"
            if $seen{$annotation->[0]}++;
    }
    die "Integer annotation follows decimal annotation\n"
        if @annotations == 2 && $annotations[0][0] ne 'integer';

    my $condition_end = @annotations ? $annotations[0][1] : length($text);
    my $condition = substr($text, 0, $condition_end);
    $condition =~ s/\A\s+|\s+\z//g;
    my $integer = '';
    my $decimal = '';
    for my $index (0 .. $#annotations) {
        my $type = $annotations[$index][0];
        my $content_start = $annotations[$index][2];
        my $content_end = $index == $#annotations
            ? length($text)
            : $annotations[$index + 1][1];
        my $sample_text = substr($text, $content_start, $content_end - $content_start);
        $sample_text =~ s/\A\s+|\s+\z//g;
        if ($type eq 'integer') {
            $integer = $sample_text;
        }
        else {
            $decimal = $sample_text;
        }
    }
    return ($condition, $integer, $decimal);
}

sub parse_samples {
    my ($text, $locale, $category) = @_;
    my (@plain, @compact);
    my $infinite = 0;
    for my $sample (grep { length } map { s/\A\s+|\s+\z//gr } split /,/, $text) {
        if ($sample eq "\x{2026}") {
            $infinite = 1;
            next;
        }
        if ($sample =~ /\A[0-9]+(?:~[0-9]+)?\z/) {
            push @plain, $sample;
        }
        elsif ($sample =~ /\A[0-9]+[cC][0-9]+\z/) {
            push @compact, $sample;
        }
        else {
            die "Unsupported integer sample '$sample' for $locale/$category\n";
        }
    }
    return { values => \@plain, compact => \@compact, infinite => $infinite };
}

sub canonical_rule_set {
    my ($rules) = @_;
    return join "\n", map {
        my $r = $rules->{$_};
        join "\x1f", $_, $r->{condition}, @{$r->{integer_samples}{values}},
            '|compact|', @{$r->{integer_samples}{compact}},
            '|infinite|', $r->{integer_samples}{infinite}, '|decimal|',
            $r->{decimal_samples_text};
    } grep { exists $rules->{$_} } @categories;
}

sub usage {
    my ($status) = @_;
    print STDERR <<'USAGE';
Usage: perl Porting/update_cldr.pl [--source-dir cldr-core-dir]
       perl Porting/update_cldr.pl [--check]
       perl Porting/update_cldr.pl --help

Import a local cldr-core JSON package or regenerate from retained inputs.
The default output directory is lib/unicore/cldr. --check verifies plural.pl
against the retained JSON files without writing files.
USAGE
    exit $status;
}
